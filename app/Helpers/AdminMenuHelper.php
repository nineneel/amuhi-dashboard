    /**
     * @return array<int, array{title: string, items: list<array{name: string, icon: string, path: string, badge_count?: int}>}>
     */
    public static function getMenuGroups(?User $user = null): array
    {
        $pendingPaymentApprovalsCount = self::getPendingPaymentApprovalsCount();

        $menuGroups = [
            [
                'title' => __('ui.admin.dashboard'),
                'items' => [
                    ['name' => __('ui.admin.overview'), 'icon' => 'dashboard', 'path' => '/admin'],
                ],
            ],
            [
                'title' => __('ui.admin.content'),
                'items' => [
                    ['name' => __('ui.admin.news'), 'icon' => 'news', 'path' => '/admin/news'],
                    ['name' => __('ui.admin.testimonies'), 'icon' => 'quote', 'path' => '/admin/testimonies'],
                ],
            ],
            [
                'title' => __('ui.admin.portal'),
                'items' => [
                    ['name' => __('ui.admin.users'), 'icon' => 'users', 'path' => '/admin/users'],
                    ['name' => __('ui.admin.events'), 'icon' => 'calendar', 'path' => '/admin/events'],
                    ['name' => __('ui.admin.subscriptions'), 'icon' => 'subscription', 'path' => '/admin/subscriptions'],
                ],
            ],
            [
                'title' => __('ui.admin.payment_menu'),
                'items' => [
                    ['name' => __('ui.admin.invoices'), 'icon' => 'invoice', 'path' => '/admin/invoices'],
                    ['name' => __('ui.admin.payments'), 'icon' => 'payment', 'path' => '/admin/payments'],
                    ['name' => __('ui.admin.payment_approvals'), 'icon' => 'check-circle', 'path' => '/admin/payment-approvals', 'badge_count' => $pendingPaymentApprovalsCount],
                ],
            ],
        ];

        if ($user?->isSuperAdmin()) {
            $menuGroups[] = [
                'title' => __('ui.admin.admin'),
                'items' => [
                    ['name' => __('ui.admin.admins'), 'icon' => 'shield', 'path' => '/admin/admins'],
                ],
            ];
        }

        $menuGroups[] = [
            'title' => __('ui.admin.settings'),
            'items' => [
                ['name' => __('ui.admin.site_settings'), 'icon' => 'settings', 'path' => '/admin/settings'],
                ['name' => __('ui.admin.profile'), 'icon' => 'user', 'path' => '/admin/profile'],
            ],
        ];

        $disabledMenuPaths = self::temporarilyDisabledMenuPaths();

        return array_values(array_filter(array_map(
            static function (array $menuGroup) use ($disabledMenuPaths): array {
                $menuGroup['items'] = array_values(array_filter(
                    $menuGroup['items'],
                    static fn (array $item): bool => ! in_array($item['path'], $disabledMenuPaths, true),
                ));

                return $menuGroup;
            },
            $menuGroups,
        ), static fn (array $menuGroup): bool => $menuGroup['items'] !== []));
    }

    /**
     * @return list<string>
     */
    private static function temporarilyDisabledMenuPaths(): array
    {
        return [
            '/admin/news',
            '/admin/testimonies',
            '/admin/events',
            '/admin/profile',
        ];
    }

    public static function getPendingPaymentApprovalsCount(): int
    {
        return Payment::query()
            ->where('payment_method', 'manual')
            ->whereHas('latestApprovalHistory', function ($query): void {
                $query->where('new_approval_status', PaymentApprovalStatus::PendingReview->value);
            })
            ->count();
    }

